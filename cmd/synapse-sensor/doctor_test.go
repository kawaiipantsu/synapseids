// A correctly deployed sensor must produce no [FAIL] line at all. This is the
// test that pins the whole happy path, including the one thing the plugin was
// missing before #104: rendered, parseable, correctly-permissioned PEM material.
func TestDoctorHealthyDeployment(t *testing.T) {
	f := newDoctorFixture(t)
	f.writeConf(t, nil, f.goodArgs(t))

	results := runChecks(f.env)
	for _, r := range results {
		if r.status == statusFail {
			t.Errorf("unexpected FAIL %s: %s", r.name, r.detail)
		}
	}
	for _, name := range []string{"binary", "config", "interface", "token-file", "tls-identity", "tls-trust", "log-sink", "collector"} {
		if _, _, ok := statusOf(results, name); !ok {
			t.Errorf("missing check %q; got %v", name, names(results))
		}
	}
	wantStatus(t, results, "config", statusPass)
	wantStatus(t, results, "interface", statusPass)
	wantStatus(t, results, "token-file", statusPass)
	wantStatus(t, results, "tls-identity", statusPass)
	wantStatus(t, results, "tls-trust", statusPass)
	wantStatus(t, results, "log-sink", statusPass)

	var sb strings.Builder
	if code := reportDoctor(&sb, results); code != 0 {
		t.Errorf("reportDoctor exit = %d, want 0\n%s", code, sb.String())
	}
	if !strings.Contains(sb.String(), "selftest: PASSED") {
		t.Errorf("output lacks the PASSED summary:\n%s", sb.String())
	}
	t.Logf("healthy deployment selftest output:\n%s", sb.String())
}

// The interface check is the one issue #102 calls out as "silently produces a
// sensor bound to nothing", so it gets its own table.
func TestDoctorInterfaceResolution(t *testing.T) {
	t.Run("device does not exist", func(t *testing.T) {
		f := newDoctorFixture(t)
		f.iface = "definitely-not-a-device0"
		f.writeConf(t, nil, "--listen 127.0.0.1:"+freePort(t)+" --iface definitely-not-a-device0 --authorized")
		results := runChecks(f.env)
		wantStatus(t, results, "interface", statusFail)
		_, detail, _ := statusOf(results, "interface")
		if !strings.Contains(detail, "does not exist") {
			t.Errorf("detail = %q, want it to name the missing device", detail)
		}
		// The remedy must enumerate what *is* present — that is the diagnostic.
		var remedy string
		for _, r := range results {
			if r.name == "interface" {
				remedy = strings.Join(r.remedy, "\n")
			}
		}
		if !strings.Contains(remedy, "Devices present:") {
			t.Errorf("remedy does not list the available devices:\n%s", remedy)
		}
	})

	t.Run("template could not resolve the identifier", func(t *testing.T) {
		f := newDoctorFixture(t)
		f.writeConf(t,
			map[string]string{"synapseids_sensor_iface_error": "identifier wan is not in the interfaces node and helpers.physical_interface is unavailable"},
			"--listen 127.0.0.1:"+freePort(t)+" --authorized")
		results := runChecks(f.env)
		wantStatus(t, results, "interface", statusFail)
		_, detail, _ := statusOf(results, "interface")
		if !strings.Contains(detail, "helpers.physical_interface") {
			t.Errorf("detail = %q, want the template's recorded lookup attempt", detail)
		}
	})

	t.Run("no interface at all", func(t *testing.T) {
		f := newDoctorFixture(t)
		f.writeConf(t, map[string]string{"synapseids_sensor_iface": ""},
			"--listen 127.0.0.1:"+freePort(t)+" --authorized")
		// writeConf writes iface before extraVars, so the later empty value wins.
		results := runChecks(f.env)
		wantStatus(t, results, "interface", statusFail)
	})
}

