func TestParseSensorConf(t *testing.T) {
	const rendered = `# Generated by OPNsense - do not edit.
synapseids_sensor_enable="YES"
synapseids_sensor_iface="em0"
synapseids_sensor_iface_id="wan"
synapseids_sensor_iface_src="interfaces.wan.if"
synapseids_sensor_iface_error=""
synapseids_sensor_args="--listen 0.0.0.0:4789 --iface em0 --filter ip-any --direction in --promisc --snaplen 262144 --sensor-id 'opnsense wan' --location 'dmz/edge' --authorized"
`
	conf, err := parseSensorConf(strings.NewReader(rendered))
	if err != nil {
		t.Fatalf("parseSensorConf: %v", err)
	}
	if !conf.enabled() {
		t.Errorf("enabled() = false, want true")
	}
	if got := conf.get("synapseids_sensor_iface"); got != "em0" {
		t.Errorf("iface = %q, want em0", got)
	}
	if got := conf.get("synapseids_sensor_iface_src"); got != "interfaces.wan.if" {
		t.Errorf("iface_src = %q", got)
	}
	if got := conf.transport(); got != "listen" {
		t.Errorf("transport = %q, want listen", got)
	}
	args := conf.args()
	for flag, want := range map[string]string{
		"--listen":    "0.0.0.0:4789",
		"--iface":     "em0",
		"--filter":    "ip-any",
		"--direction": "in",
		"--snaplen":   "262144",
		"--sensor-id": "opnsense wan",
		"--location":  "dmz/edge",
	} {
		if got := flagValue(args, flag); got != want {
			t.Errorf("flagValue(%s) = %q, want %q", flag, got, want)
		}
	}
	for _, flag := range []string{"--promisc", "--authorized"} {
		if !hasFlag(args, flag) {
			t.Errorf("hasFlag(%s) = false, want true", flag)
		}
	}
	if hasFlag(args, "--insecure-tls") {
		t.Error("hasFlag(--insecure-tls) = true, want false")
	}
	// A quoted value containing a space must not be split into two words, or the
	// sensor-id would be truncated in the daemon's capture-sources view.
	if got := len(args); got != 16 {
		t.Errorf("args length = %d (%q), want 16", got, args)
	}
}

// The rc.d script sources sensor.conf as root, so anything the shell would
// re-interpret must be rejected rather than silently accepted.
func TestParseSensorConfRejectsShellInjection(t *testing.T) {
	for name, body := range map[string]string{
		"command substitution": "a=\"x\"\nsynapseids_sensor_args=\"--iface $(id)\"\n",
		"backtick":             "a=\"x\"\nsynapseids_sensor_args=\"--iface `id`\"\n",
		"variable expansion":   "a=\"x\"\nsynapseids_sensor_args=\"--iface ${HOME}\"\n",
		"semicolon":            "a=\"x\"\nsynapseids_sensor_args=\"--iface em0; rm -rf /\"\n",
		"pipe":                 "a=\"x\"\nsynapseids_sensor_args=\"--iface em0 | sh\"\n",
		"not name=value":       "this is not a shell fragment\n",
		"bad variable name":    "9bad=\"x\"\n",
		"empty":                "# only a comment\n",
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := parseSensorConf(strings.NewReader(body)); err == nil {
				t.Fatalf("parseSensorConf(%q) succeeded, want an error", body)
			}
		})
	}
}

func TestSplitShellWords(t *testing.T) {
	for _, tc := range []struct {
		in   string
		want []string
	}{
		{"", nil},
		{"   ", nil},
		{"--a b", []string{"--a", "b"}},
		{"--a  'b c'  --d", []string{"--a", "b c", "--d"}},
		{`--a "b c"`, []string{"--a", "b c"}},
		{"--a ''", []string{"--a", ""}},
		{"\t--a\tb\t", []string{"--a", "b"}},
	} {
		got := splitShellWords(tc.in)
		if fmt.Sprint(got) != fmt.Sprint(tc.want) {
			t.Errorf("splitShellWords(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

func TestFlagValueEqualsForm(t *testing.T) {
	args := []string{"--connect=ids.example:4789", "--iface", "em0", "--cert"}
	if got := flagValue(args, "--connect"); got != "ids.example:4789" {
		t.Errorf("--connect = %q", got)
	}
	if got := flagValue(args, "--iface"); got != "em0" {
		t.Errorf("--iface = %q", got)
	}
	// A trailing flag with no value must not consume the next flag.
	if got := flagValue(args, "--cert"); got != "" {
		t.Errorf("--cert = %q, want empty", got)
	}
	if got := flagValue(args, "--nope"); got != "" {
		t.Errorf("--nope = %q, want empty", got)
	}
}

