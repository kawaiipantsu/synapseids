// reportDoctor's exit status is the contract the rc.d verb and the configd
// action rely on.
func TestReportDoctorExitStatus(t *testing.T) {
	var sb strings.Builder
	if code := reportDoctor(&sb, []checkResult{pass("a", "ok"), warn("b", "hmm", "do this"), skip("c", "n/a")}); code != 0 {
		t.Errorf("exit = %d, want 0 (a warning must not fail the run)", code)
	}
	if !strings.Contains(sb.String(), "       do this") {
		t.Errorf("remedy lines must be indented under their check:\n%s", sb.String())
	}
	sb.Reset()
	if code := reportDoctor(&sb, []checkResult{pass("a", "ok"), fail("b", "broken")}); code != 1 {
		t.Errorf("exit = %d, want 1", code)
	}
	if !strings.Contains(sb.String(), "selftest: FAILED") {
		t.Errorf("output lacks the FAILED summary:\n%s", sb.String())
	}
}

// The status labels are what an operator greps for, so pin them.
func TestCheckStatusLabels(t *testing.T) {
	for status, want := range map[checkStatus]string{
		statusPass: "[ OK ]",
		statusWarn: "[WARN]",
		statusFail: "[FAIL]",
		statusSkip: "[SKIP]",
	} {
		if got := status.label(); got != want {
			t.Errorf("label = %q, want %q", got, want)
		}
	}
}

