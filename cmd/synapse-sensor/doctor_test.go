// doctorFixture builds a temporary tree that looks like a correctly deployed
// sensor, and returns the env pointing at it.
type doctorFixture struct {
	env      doctorEnv
	etcDir   string
	logDir   string
	iface    string
	certPath string
	keyPath  string
	caPath   string
}

func newDoctorFixture(t *testing.T) *doctorFixture {
	t.Helper()
	root := t.TempDir()
	etcDir := filepath.Join(root, "etc")
	logDir := filepath.Join(root, "log")
	for _, d := range []string{etcDir, logDir} {
		if err := os.MkdirAll(d, 0o750); err != nil {
			t.Fatal(err)
		}
	}

	_, certPEM, keyPEM, err := pcapoverip.SelfSignedCert("127.0.0.1")
	if err != nil {
		t.Fatal(err)
	}
	f := &doctorFixture{
		etcDir:   etcDir,
		logDir:   logDir,
		iface:    firstLocalInterface(t),
		certPath: filepath.Join(etcDir, "sensor-cert.pem"),
		keyPath:  filepath.Join(etcDir, "sensor-key.pem"),
		caPath:   filepath.Join(etcDir, "sensor-ca.pem"),
	}
	write(t, f.certPath, certPEM, 0o444)
	write(t, f.caPath, certPEM, 0o444)
	write(t, f.keyPath, keyPEM, 0o400)
	write(t, filepath.Join(etcDir, "sensor.token"), []byte("a-bearer-token\n"), 0o400)
	write(t, filepath.Join(logDir, "sensor.log"), []byte("sensor: started\n"), 0o640)

	me, err := user.Current()
	if err != nil {
		t.Fatal(err)
	}
	f.env = doctorEnv{
		etcDir:    etcDir,
		logDir:    logDir,
		user:      me.Username,
		bpfDevs:   []string{filepath.Join(root, "no-bpf-here")},
		timeout:   2 * time.Second,
		buildInfo: "synapse-sensor 0.0.0-test",
		goos:      runtime.GOOS,
	}
	return f
}

// writeConf renders a sensor.conf with the given flag string and points the env
// at it.
func (f *doctorFixture) writeConf(t *testing.T, extraVars map[string]string, args string) {
	t.Helper()
	var b strings.Builder
	b.WriteString("# Generated by OPNsense - do not edit.\n")
	b.WriteString("synapseids_sensor_enable=\"YES\"\n")
	b.WriteString("synapseids_sensor_iface=\"" + f.iface + "\"\n")
	b.WriteString("synapseids_sensor_iface_id=\"wan\"\n")
	b.WriteString("synapseids_sensor_iface_src=\"interfaces.wan.if\"\n")
	b.WriteString("synapseids_sensor_iface_error=\"\"\n")
	for k, v := range extraVars {
		b.WriteString(k + "=\"" + v + "\"\n")
	}
	b.WriteString("synapseids_sensor_args=\"" + args + "\"\n")

	path := filepath.Join(f.etcDir, "sensor.conf")
	write(t, path, []byte(b.String()), 0o640)
	f.env.confPath = path
}

// goodArgs is a fully configured listen-mode sensor on a free port.
func (f *doctorFixture) goodArgs(t *testing.T) string {
	t.Helper()
	return strings.Join([]string{
		"--listen 127.0.0.1:" + freePort(t),
		"--iface " + f.iface,
		"--filter ip-any",
		"--direction in",
		"--authorized",
		"--cert " + f.certPath,
		"--key " + f.keyPath,
		"--client-ca " + f.caPath,
		"--token-file " + filepath.Join(f.etcDir, "sensor.token"),
	}, " ")
}

func write(t *testing.T, path string, data []byte, mode os.FileMode) {
	t.Helper()
	if err := os.WriteFile(path, data, mode); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(path, mode); err != nil {
		t.Fatal(err)
	}
}

func firstLocalInterface(t *testing.T) string {
	t.Helper()
	ifaces, err := net.Interfaces()
	if err != nil || len(ifaces) == 0 {
		t.Skip("no network interfaces to test against")
	}
	for _, i := range ifaces {
		if i.Flags&net.FlagUp != 0 {
			return i.Name
		}
	}
	return ifaces[0].Name
}

func freePort(t *testing.T) string {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = ln.Close() }()
	_, port, err := net.SplitHostPort(ln.Addr().String())
	if err != nil {
		t.Fatal(err)
	}
	return port
}

// statusOf returns the status of the named check, and whether it was present.
func statusOf(results []checkResult, name string) (checkStatus, string, bool) {
	for _, r := range results {
		if r.name == name {
			return r.status, r.detail, true
		}
	}
	return 0, "", false
}

func wantStatus(t *testing.T, results []checkResult, name string, want checkStatus) {
	t.Helper()
	got, detail, ok := statusOf(results, name)
	if !ok {
		t.Fatalf("check %q not present in %v", name, names(results))
	}
	if got != want {
		t.Errorf("check %q = %s (%s), want %s", name, got.label(), detail, want.label())
	}
}

func names(results []checkResult) []string {
	out := make([]string, 0, len(results))
	for _, r := range results {
		out = append(out, r.name)
	}
	return out
}

