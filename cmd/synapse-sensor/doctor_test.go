// #104: the private key must never be readable by anyone but the service user,
// and a missing PEM must stay a hard failure rather than a downgrade.
func TestDoctorTLSMaterial(t *testing.T) {
	t.Run("key world readable", func(t *testing.T) {
		f := newDoctorFixture(t)
		if err := os.Chmod(f.keyPath, 0o444); err != nil {
			t.Fatal(err)
		}
		f.writeConf(t, nil, f.goodArgs(t))
		results := runChecks(f.env)
		wantStatus(t, results, "tls-identity", statusFail)
		_, detail, _ := statusOf(results, "tls-identity")
		if !strings.Contains(detail, "readable by more than its owner") {
			t.Errorf("detail = %q", detail)
		}
	})

	t.Run("key missing is a hard failure", func(t *testing.T) {
		f := newDoctorFixture(t)
		if err := os.Remove(f.keyPath); err != nil {
			t.Fatal(err)
		}
		f.writeConf(t, nil, f.goodArgs(t))
		results := runChecks(f.env)
		wantStatus(t, results, "tls-identity", statusFail)
	})

	t.Run("mismatched pair", func(t *testing.T) {
		f := newDoctorFixture(t)
		_, _, otherKey, err := pcapoverip.SelfSignedCert("127.0.0.1")
		if err != nil {
			t.Fatal(err)
		}
		write(t, f.keyPath, otherKey, 0o400)
		f.writeConf(t, nil, f.goodArgs(t))
		results := runChecks(f.env)
		wantStatus(t, results, "tls-identity", statusFail)
	})

	t.Run("half a pair", func(t *testing.T) {
		f := newDoctorFixture(t)
		f.writeConf(t, nil, "--listen 127.0.0.1:"+freePort(t)+" --iface "+f.iface+
			" --authorized --cert "+f.certPath)
		results := runChecks(f.env)
		wantStatus(t, results, "tls-identity", statusFail)
	})

	t.Run("a private key pasted into the CA field", func(t *testing.T) {
		f := newDoctorFixture(t)
		_, _, keyPEM, err := pcapoverip.SelfSignedCert("127.0.0.1")
		if err != nil {
			t.Fatal(err)
		}
		write(t, f.caPath, keyPEM, 0o444)
		f.writeConf(t, nil, f.goodArgs(t))
		results := runChecks(f.env)
		wantStatus(t, results, "tls-trust", statusFail)
		_, detail, _ := statusOf(results, "tls-trust")
		if !strings.Contains(detail, "not a certificate") {
			t.Errorf("detail = %q", detail)
		}
	})

	t.Run("no TLS material configured", func(t *testing.T) {
		f := newDoctorFixture(t)
		f.writeConf(t, nil, "--listen 127.0.0.1:"+freePort(t)+" --iface "+f.iface+" --authorized")
		results := runChecks(f.env)
		wantStatus(t, results, "tls-identity", statusSkip)
		wantStatus(t, results, "tls-trust", statusSkip)
	})

	t.Run("insecure-tls warns loudly", func(t *testing.T) {
		f := newDoctorFixture(t)
		f.writeConf(t, nil, "--connect 127.0.0.1:"+freePort(t)+" --iface "+f.iface+
			" --authorized --insecure-tls")
		f.env.skipDial = true
		results := runChecks(f.env)
		wantStatus(t, results, "tls-trust", statusWarn)
		_, detail, _ := statusOf(results, "tls-trust")
		if !strings.Contains(detail, "NOT verified") {
			t.Errorf("detail = %q", detail)
		}
	})
}

